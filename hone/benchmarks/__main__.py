"""Command-line entry point: `python -m hone.benchmarks`."""
import argparse
import sys
import time
from importlib.metadata import version

from .problems import quick_problems, standard_problems
from .runner import load_summaries, regressions, run_benchmark, save_summaries, summarize, to_markdown


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m hone.benchmarks", description=__doc__)
    parser.add_argument("--quick", action="store_true", help="run the small CI subset with fewer seeds and evaluations")
    parser.add_argument("--seeds", type=int, help="number of seeds per problem (default 10, or 5 with --quick)")
    parser.add_argument("--budget-per-dimension", type=int, help="evaluations per dimension (default 1000, or 200 with --quick)")
    parser.add_argument("--tolerance", type=float, default=1e-4, help="error at or below which a run counts as solved")
    parser.add_argument("--markdown", help="write the results table to this file")
    parser.add_argument("--save", help="write the summaries as JSON to this file, for use as a baseline")
    parser.add_argument("--baseline", help="compare against summaries saved with --save; exit 1 on a regression")
    args = parser.parse_args(argv)

    problems = quick_problems() if args.quick else standard_problems()
    seeds = args.seeds or (5 if args.quick else 10)
    budget = args.budget_per_dimension or (200 if args.quick else 1000)

    start = time.perf_counter()
    summaries = summarize(run_benchmark(problems, seeds=range(seeds), budget_per_dimension=budget), args.tolerance)
    elapsed = time.perf_counter() - start

    table = to_markdown(summaries, args.tolerance)
    print(table)
    print(f"{len(problems)} problems, {seeds} seeds, {budget} evaluations per dimension, in {elapsed:.0f}s")
    if args.markdown:
        with open(args.markdown, "w") as f:
            f.write(
                f"# Benchmark results\n\nGenerated by `python -m hone.benchmarks` with hone {version('hone')}: "
                f"{len(problems)} problems, {seeds} seeds, {budget} evaluations per dimension.\n\n{table}"
            )
    if args.save:
        save_summaries(summaries, args.save)

    if args.baseline:
        found = regressions(summaries, load_summaries(args.baseline))
        if found:
            print("\nRegressions against the baseline:", *found, sep="\n  ")
            return 1
        print("\nNo regressions against the baseline.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
