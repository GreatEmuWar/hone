"""Command-line entry point: `python -m hone.benchmarks`."""
import argparse
import sys
import time
from collections.abc import Sequence
from importlib.metadata import version

from . import ml
from .conditional import conditional_problems
from .multi import multi_markdown, multi_problems, run_multi_benchmark, summarize_multi
from .constrained import constrained_problems
from .problems import noisy_problems, quick_problems, standard_problems
from .runner import BUDGETS, load_summaries, regressions, run_benchmark, save_summaries, summarize, to_markdown


QUICK_BUDGETS = (10, 50, 200)
NOISY_BUDGETS = (10, 40, 200)


def _join(numbers: list[int]) -> str:
    """[10, 20, 50] -> "10, 20 and 50"."""
    words = [f"{n:,}" for n in numbers]
    return words[0] if len(words) == 1 else ", ".join(words[:-1]) + " and " + words[-1]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m hone.benchmarks", description=__doc__)
    suite = parser.add_mutually_exclusive_group()
    suite.add_argument("--quick", action="store_true", help="run the small CI subset with fewer seeds and evaluations")
    suite.add_argument("--ml", action="store_true", help="run the machine learning tuning problems instead (needs scikit-learn)")
    suite.add_argument("--noisy", action="store_true", help="run the problems with noise added to every evaluation instead")
    suite.add_argument("--constrained", action="store_true", help="run the problems with constraints instead")
    suite.add_argument(
        "--multi", action="store_true", help="run the problems with several objectives instead, scored by hypervolume"
    )
    suite.add_argument(
        "--conditional", action="store_true", help="run the problems with conditional parameters, and their flat versions, instead"
    )
    parser.add_argument("--seeds", type=int, help="number of seeds per problem (default 10, or 5 with --quick)")
    parser.add_argument(
        "--budgets",
        type=int,
        nargs="+",
        help=f"evaluations per dimension, one run per budget (default {' '.join(map(str, BUDGETS))}, "
        f"{' '.join(map(str, QUICK_BUDGETS))} with --quick, {' '.join(map(str, ml.BUDGETS))} with --ml, "
        f"or {' '.join(map(str, NOISY_BUDGETS))} with --noisy)",
    )
    parser.add_argument("--jobs", type=int, default=1, help="share the runs among this many processes (Linux only)")
    parser.add_argument("--tolerance", type=float, default=1e-4, help="error at or below which a run counts as solved")
    parser.add_argument("--markdown", help="write the results table to this file")
    parser.add_argument("--save", help="write the summaries as JSON to this file, for use as a baseline")
    parser.add_argument("--baseline", help="compare against summaries saved with --save; exit 1 on a regression")
    args = parser.parse_args(argv)

    if args.multi:
        return _multi(args)
    default_budgets: Sequence[int]
    if args.quick:
        problems, default_budgets = quick_problems(), QUICK_BUDGETS
    elif args.ml:
        problems, default_budgets = ml.ml_problems(), ml.BUDGETS
    elif args.noisy:
        problems, default_budgets = noisy_problems(), NOISY_BUDGETS
    elif args.constrained:
        problems, default_budgets = constrained_problems(), BUDGETS
    elif args.conditional:
        problems, default_budgets = conditional_problems(), BUDGETS
    else:
        problems, default_budgets = standard_problems(), BUDGETS
    seeds = args.seeds or (5 if args.quick else 10)
    budgets = sorted(set(args.budgets or default_budgets))

    start = time.perf_counter()
    summaries = summarize(run_benchmark(problems, seeds=range(seeds), budgets_per_dimension=budgets, jobs=args.jobs), args.tolerance)
    elapsed = time.perf_counter() - start

    table = to_markdown(summaries, args.tolerance)
    print(table)
    setup = f"{len(problems)} problems, {seeds} seeds, budgets of {_join(budgets)} evaluations per dimension"
    print(f"{setup}, in {elapsed:.0f}s")
    if args.markdown:
        with open(args.markdown, "w") as f:
            f.write(
                f"# Benchmark results\n\nGenerated by `python -m hone.benchmarks` with hone {version('hone-python')}: "
                f"{setup}.\n\n{table}"
            )
    if args.save:
        save_summaries(summaries, args.save)

    if args.baseline:
        found = regressions(summaries, load_summaries(args.baseline))
        if found:
            print("\nRegressions against the baseline:", *found, sep="\n  ")
            return 1
        print("\nNo regressions against the baseline.")
    return 0


def _multi(args: argparse.Namespace) -> int:
    """The multi-objective suite: its own runs, scored by hypervolume gap."""
    problems = multi_problems()
    seeds = args.seeds or 10
    budgets = sorted(set(args.budgets or BUDGETS))
    start = time.perf_counter()
    summaries = summarize_multi(run_multi_benchmark(problems, seeds=range(seeds), budgets_per_dimension=budgets, jobs=args.jobs))
    elapsed = time.perf_counter() - start
    table = multi_markdown(summaries)
    print(table)
    setup = f"{len(problems)} problems, {seeds} seeds, budgets of {_join(budgets)} evaluations per dimension"
    print(f"{setup}, in {elapsed:.0f}s")
    if args.markdown:
        with open(args.markdown, "w") as f:
            f.write(f"# Multi-objective benchmark results\n\nGenerated by `python -m hone.benchmarks --multi` with hone {version('hone-python')}: {setup}.\n\n{table}")
    if args.save:
        with open(args.save, "w") as f:
            f.write("[\n" + ",\n".join(s.model_dump_json() for s in summaries) + "\n]\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
